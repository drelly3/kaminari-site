// Generates deploy/worker.generated.js: a self-contained Worker that serves only The Anime Mindset's own
// pages and assets. No bindings, no storage, no APIs, no form handling.
//
//   node animemindset-site/deploy/build-worker.mjs
//
// Text files (HTML, CSS, JS, SVG) are embedded as strings. Images are imported as binary Data modules
// (see the "rules" in deploy/wrangler.jsonc) so they are uploaded as-is, not base64-encoded.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DEPLOY = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(DEPLOY, '..');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8',
};
const BINARY = new Set(['.png', '.webp']);

// The allowlist: the pages, robots.txt and sitemap.xml, plus every file under assets/. Nothing else in the folder is served.
const PAGES = ['index.html', 'about.html', 'coaching.html', 'newsletter.html', 'privacy-policy.html', 'quiz.html', 'robots.txt', 'sitemap.xml'];
// Pages kept out of search engines on every host (the owner asked for coaching to stay noindex).
const NOINDEX = ['/coaching.html'];
const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(e =>
  e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]);
const files = [...PAGES.map(p => path.join(SITE, p)), ...walk(path.join(SITE, 'assets'))]
  .map(abs => path.relative(SITE, abs).split(path.sep).join('/'))
  .sort();

const imports = [], entries = [];
files.forEach((rel, i) => {
  const ext = path.extname(rel).toLowerCase();
  const type = TYPES[ext];
  if (!type) throw new Error(`No MIME type for ${rel}; add it to TYPES or remove the file.`);
  if (BINARY.has(ext)) {
    imports.push(`import f${i} from ${JSON.stringify('../' + rel)};`);
    entries.push(`  [${JSON.stringify('/' + rel)}, { type: ${JSON.stringify(type)}, body: f${i} }],`);
  } else {
    const text = fs.readFileSync(path.join(SITE, rel), 'utf8');
    entries.push(`  [${JSON.stringify('/' + rel)}, { type: ${JSON.stringify(type)}, body: ${JSON.stringify(text)} }],`);
  }
});

const out = `// GENERATED by deploy/build-worker.mjs from animemindset-site/. Do not edit by hand.
// Serves only the files listed in FILES (plus "/" for the homepage). Everything else is a 404.
${imports.join('\n')}

const FILES = new Map([
${entries.join('\n')}
]);

const ALIASES = new Map([['/', '/index.html']]);

const NOINDEX = new Set(${JSON.stringify(NOINDEX)});

const BASE_HEADERS = {
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
};

// The workers.dev address is a duplicate of animemindset.com, so it is always kept out of search engines.
const robots = (host, path) => host.endsWith('.workers.dev') || NOINDEX.has(path) ? { 'X-Robots-Tag': 'noindex, nofollow' } : {};

const plain = (status, text, extra = {}) => new Response(text, {
  status,
  headers: { ...BASE_HEADERS, 'X-Robots-Tag': 'noindex, nofollow', 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store', ...extra },
});

export default {
  async fetch(request) {
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return plain(405, 'Method Not Allowed', { Allow: 'GET, HEAD' });
    }
    const { pathname, hostname } = new URL(request.url);
    const path = ALIASES.get(pathname) || pathname;
    const file = FILES.get(path);
    if (!file) return plain(404, 'Not found');
    const headers = {
      ...BASE_HEADERS,
      ...robots(hostname, path),
      'Content-Type': file.type,
      'Cache-Control': file.type.startsWith('text/html') ? 'no-cache' : 'public, max-age=3600',
    };
    return new Response(request.method === 'HEAD' ? null : file.body, { headers });
  },
};
`;
fs.writeFileSync(path.join(DEPLOY, 'worker.generated.js'), out);
console.log(`worker.generated.js: ${files.length} files (${imports.length} binary, ${files.length - imports.length} text)`);
files.forEach(f => console.log('  /' + f));
